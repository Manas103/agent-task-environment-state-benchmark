"""Runs the full 420-task corpus through the real gateway twice: once clean,
once with a deliberately injected 50ms synthetic delay on exactly one tool
(escalate_ticket), and aggregates the per-step OpenTelemetry spans both
times by tool. The point is not the delay itself (that number is chosen,
not measured) but whether per-tool span attribution can isolate which one
of 13 tools regressed from spans alone; see docs/span_regression_output.txt
and the README's Findings for the result.

Usage: python scripts/run_span_capture.py
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts import server_manager
from src import db
from src.executor.executor import PlanExecutor
from src.tasks.task_generator import generate_all

REGRESSION_TOOL = "escalate_ticket"
REGRESSION_DELAY_MS = 50
DOCS_DIR = Path(__file__).resolve().parents[1] / "docs"


def _run_pass(label: str, jsonl_path: Path, regression_tool: str | None, delay_ms: int) -> None:
    import os

    for schema in ("crm", "ticketing", "inventory"):
        db.reset_schema(schema)

    env_overrides = {"AGENTENV_OTEL_OUT": str(jsonl_path)}
    if regression_tool:
        env_overrides["AGENTENV_REGRESSION_TOOL"] = regression_tool
        env_overrides["AGENTENV_REGRESSION_DELAY_MS"] = str(delay_ms)

    old_env = {k: os.environ.get(k) for k in env_overrides}
    os.environ.update(env_overrides)
    try:
        procs = server_manager.start_all()
        try:
            executor = PlanExecutor(procs["gateway"]["url"])
            tasks = generate_all()
            for task in tasks:
                executor.execute(task.id, task.instruction, task.executed_plan)
        finally:
            server_manager.stop_all(procs)
    finally:
        for k, v in old_env.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v
    print(f"{label}: {len(tasks)} tasks replayed, spans written to {jsonl_path}")


def _aggregate(jsonl_path: Path) -> dict:
    by_tool = defaultdict(lambda: {"n": 0, "latency_ms_total": 0.0, "tokens_total": 0, "cost_usd_total": 0.0})
    with open(jsonl_path) as f:
        for line in f:
            row = json.loads(line)
            attrs = row["attributes"]
            tool = attrs["gen_ai.tool.name"]
            agg = by_tool[tool]
            agg["n"] += 1
            agg["latency_ms_total"] += attrs["agentbench.latency_ms"]
            agg["tokens_total"] += attrs["agentbench.request_tokens"] + attrs["agentbench.response_tokens"]
            agg["cost_usd_total"] += attrs["agentbench.cost_usd"]
    return {
        tool: {
            "n": v["n"],
            "mean_latency_ms": round(v["latency_ms_total"] / v["n"], 3),
            "mean_tokens": round(v["tokens_total"] / v["n"], 1),
            "total_cost_usd": round(v["cost_usd_total"], 6),
        }
        for tool, v in sorted(by_tool.items())
    }


def _write_sample(full_path: Path, sample_path: Path, n: int = 130) -> None:
    """Commits a representative first-N-line sample instead of the full
    1,260-span capture (full files are regenerated by this script, not
    tracked; see .gitignore). N=130 covers every one of the 13 tools several
    times over, which is enough to inspect real span shapes without the
    repo carrying 450KB per run."""
    with open(full_path) as src, open(sample_path, "w") as dst:
        for i, line in enumerate(src):
            if i >= n:
                break
            dst.write(line)


def main() -> None:
    DOCS_DIR.mkdir(exist_ok=True)
    baseline_path = DOCS_DIR / "otel_spans_baseline.jsonl"
    regressed_path = DOCS_DIR / "otel_spans_regressed.jsonl"
    baseline_path.unlink(missing_ok=True)
    regressed_path.unlink(missing_ok=True)

    _run_pass("baseline", baseline_path, regression_tool=None, delay_ms=0)
    _run_pass("regressed", regressed_path, regression_tool=REGRESSION_TOOL, delay_ms=REGRESSION_DELAY_MS)

    _write_sample(baseline_path, DOCS_DIR / "otel_spans_baseline_sample.jsonl")
    _write_sample(regressed_path, DOCS_DIR / "otel_spans_regressed_sample.jsonl")

    baseline_agg = _aggregate(baseline_path)
    regressed_agg = _aggregate(regressed_path)

    lines = []
    lines.append("=== Per-tool span attribution: baseline vs. one injected 50ms regression on escalate_ticket ===\n")
    lines.append(f"{'tool':<22}{'baseline ms':>14}{'regressed ms':>15}{'delta ms':>12}{'delta %':>10}")
    flagged = []
    for tool in sorted(set(baseline_agg) | set(regressed_agg)):
        b = baseline_agg.get(tool, {}).get("mean_latency_ms", 0.0)
        r = regressed_agg.get(tool, {}).get("mean_latency_ms", 0.0)
        delta = r - b
        pct = (100.0 * delta / b) if b else 0.0
        lines.append(f"{tool:<22}{b:>14.3f}{r:>15.3f}{delta:>12.3f}{pct:>9.1f}%")
        if abs(pct) > 20.0:
            flagged.append(tool)

    lines.append("")
    lines.append(f"tools flagged as changed by more than 20%: {flagged}")
    lines.append(f"injected regression was on: {REGRESSION_TOOL} (+{REGRESSION_DELAY_MS}ms, disclosed and synthetic)")
    lines.append(f"correctly isolated to exactly the injected tool: {flagged == [REGRESSION_TOOL]}")
    lines.append("")
    lines.append("per-tool token and cost totals (baseline run, same proxy estimator both runs):")
    for tool, v in baseline_agg.items():
        lines.append(f"  {tool}: n={v['n']} mean_tokens={v['mean_tokens']} total_cost_usd={v['total_cost_usd']}")

    out_text = "\n".join(lines)
    print(out_text)
    (DOCS_DIR / "span_regression_output.txt").write_text(out_text + "\n", encoding="utf-8")
    (DOCS_DIR / "span_regression_summary.json").write_text(
        json.dumps({"baseline": baseline_agg, "regressed": regressed_agg, "flagged": flagged}, indent=2),
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
