def other_than(pool, value):
    """Return a pool entry that is a different, still-valid value than `value`.
    Used to construct the injected mistake: a syntactically fine, semantically
    wrong argument, never a tool error."""
    idx = pool.index(value) if value in pool else 0
    return pool[(idx + 1) % len(pool)]


def company_name(i: int) -> str:
    return f"{COMPANY_WORDS[i % len(COMPANY_WORDS)]} {i:04d}"


def contact_name(i: int) -> str:
    return f"{CONTACT_FIRST[i % len(CONTACT_FIRST)]} {CONTACT_LAST[(i * 3) % len(CONTACT_LAST)]}"


def product_name(i: int) -> str:
    return f"{PRODUCT_WORDS[i % len(PRODUCT_WORDS)]} {i:04d}"


def ticket_subject(i: int) -> str:
    return f"{TICKET_SUBJECTS[i % len(TICKET_SUBJECTS)]} #{i:04d}"
